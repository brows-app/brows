namespace Brows.Triggers;

/// <summary>
/// Identifies a mouse button in a click gesture.
/// </summary>
public enum ClickButton {
    /// <summary>
    /// No mouse button.
    /// </summary>
    None = -1,

    /// <summary>
    /// The left mouse button.
    /// </summary>
    Left = 0,

    /// <summary>
    /// The middle mouse button.
    /// </summary>
    Middle = 1,

    /// <summary>
    /// The right mouse button.
    /// </summary>
    Right = 2
}
