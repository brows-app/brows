namespace Brows.Entries;

/// <summary>
/// Specifies horizontal alignment for an entry data value.
/// </summary>
public enum EntryDataAlignment {
    /// <summary>
    /// Uses the view's default alignment.
    /// </summary>
    Default,

    /// <summary>
    /// Aligns the value to the left.
    /// </summary>
    Left,

    /// <summary>
    /// Aligns the value to the right.
    /// </summary>
    Right
}
